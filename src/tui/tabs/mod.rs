//! Right-pane tab implementations.
//!
//! Each tab is a small self-contained module so the per-tab state
//! and render code stays close together. The [`RightTab`] enum is
//! the single shared identifier; `tabs_for_mode` resolves the set
//! of tabs reachable for a given model mode hint.

pub mod chat;
pub mod embed;
pub mod input_pane;
pub mod logs;
pub mod requests;
pub mod rerank;
pub mod settings;

use crate::gguf::metadata::ModeHint;

/// Identifier for one right-pane tab. `Settings` and `Logs` are
/// always reachable for a model that has a launch; the
/// mode-specific tabs become reachable when the focused model is
/// `Ready` and its `ModeHint` matches. Variant order matches the
/// user-facing tab strip: Requests leads, then Logs, then Settings,
/// then the mode tab.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RightTab {
  /// The proxy requests of the focused model.
  Requests,
  Logs,
  /// Launch-parameter form. Editable for not-yet-launched models;
  /// read-only for running models (shows the params used).
  Settings,
  Chat,
  Embed,
  Rerank,
}

impl RightTab {
  pub fn label(&self) -> &'static str {
    match self {
      RightTab::Settings => "Settings",
      RightTab::Logs => "Logs",
      RightTab::Chat => "Chat",
      RightTab::Embed => "Embed",
      RightTab::Rerank => "Rerank",
      RightTab::Requests => "Requests",
    }
  }

  /// Index in [`Self::label`] of the letter underlined as the tab's
  /// Shift quick-jump key. The first letter, except for `Requests`:
  /// `R` already jumps to Rerank, so it takes its `q`.
  pub fn mnemonic_index(&self) -> usize {
    match self {
      RightTab::Requests => 2,
      _ => 0,
    }
  }
}

/// One-off events generated by async tab tasks (embed, rerank).
/// Lives here rather than in `tui::events` so per-tab modules
/// (`tabs::embed`, `tabs::rerank`) don't need to reach up into the
/// event-loop module. The chat tab streams via its own
/// `ChatStreamMsg` channel held inside `ChatTabState`; embed/rerank
/// only need a single result message so the receivers live on their
/// respective tab states.
#[derive(Debug)]
pub enum TabEvent {
  EmbedOk(crate::tui::oai_client::EmbedResult),
  EmbedErr(String),
  RerankOk(Vec<(usize, f64)>),
  RerankErr(String),
}

/// The strip of any managed launch, before a mode surface is added:
/// Requests leads because what a live model is doing matters more
/// than how it was configured, Logs follows so the process pipeline
/// is one Tab away, and Settings closes the strip.
pub fn tabs_without_mode() -> Vec<RightTab> {
  vec![RightTab::Requests, RightTab::Logs, RightTab::Settings]
}

/// Tabs available for a model with the supplied mode hint. The
/// renderer only exposes the second tab when the model is `Ready`;
/// this helper just declares which tab type is appropriate.
pub fn tabs_for_mode(mode: ModeHint) -> Vec<RightTab> {
  let mut tabs = tabs_without_mode();
  match mode {
    ModeHint::Chat => tabs.push(RightTab::Chat),
    ModeHint::Embedding => tabs.push(RightTab::Embed),
    ModeHint::Rerank => tabs.push(RightTab::Rerank),
    ModeHint::Image | ModeHint::Tts | ModeHint::Stt | ModeHint::Unknown => {}
  }
  tabs
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn requests_leads_the_strip_and_the_mode_tab_closes_it() {
    use RightTab::{Chat, Embed, Logs, Requests, Rerank, Settings};
    assert_eq!(
      tabs_for_mode(ModeHint::Chat),
      vec![Requests, Logs, Settings, Chat]
    );
    assert_eq!(
      tabs_for_mode(ModeHint::Embedding),
      vec![Requests, Logs, Settings, Embed]
    );
    assert_eq!(
      tabs_for_mode(ModeHint::Rerank),
      vec![Requests, Logs, Settings, Rerank]
    );
    assert_eq!(
      tabs_for_mode(ModeHint::Unknown),
      vec![Requests, Logs, Settings]
    );
    assert_eq!(tabs_without_mode(), vec![Requests, Logs, Settings]);
  }

  #[test]
  fn every_visible_tab_set_has_distinct_mnemonic_letters() {
    for mode in [
      ModeHint::Chat,
      ModeHint::Embedding,
      ModeHint::Rerank,
      ModeHint::Unknown,
    ] {
      let mut letters: Vec<char> = tabs_for_mode(mode)
        .iter()
        .map(|t| {
          t.label()
            .chars()
            .nth(t.mnemonic_index())
            .unwrap()
            .to_ascii_uppercase()
        })
        .collect();
      let total = letters.len();
      letters.sort_unstable();
      letters.dedup();
      assert_eq!(letters.len(), total, "{mode:?}: {letters:?}");
    }
  }
}
